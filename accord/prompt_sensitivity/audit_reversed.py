"""Audit of C103 llama3:8b / P_reversed AUROC 0.7503 (aggregates only).

Reads the local per-pair cache and gold labels; writes ONLY aggregates to
results/accord/prompt_sensitivity/audit_reversed.json. Run with stdout and
stderr redirected to ~/mimic_local_only/logs/audit_reversed.log.
"""
import json
import pathlib
import sys

import numpy as np
import pandas as pd
from scipy.stats import mannwhitneyu
from sklearn.metrics import roc_auc_score

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from accord.prompt_sensitivity.prompts import PROMPTS  # noqa: E402

HOME = pathlib.Path.home()
GOLD = HOME / "mimic_local_only/from_drive_2026-08-08/outputs/pharmacist_labeled_clean.csv"
DERIVED = HOME / "mimic_local_only/derived/gold_standard_accord_results.csv"
CACHE = HOME / "mimic_local_only/accord_prompt_sensitivity_cache"
ANALYSIS = ROOT / "results/accord/prompt_sensitivity/analysis.json"
OUT = ROOT / "results/accord/prompt_sensitivity/audit_reversed.json"
TAGS = {"llama3:8b": "_llama3_8b_nothink", "granite3.3:8b": "_granite33_8b_nothink",
        "qwen3:8b": "_qwen3_8b_nothink"}
MDE = 0.7355


def load(tag, prompt):
    p = CACHE / f"{tag}__{prompt}.jsonl"
    return {r["pair_id"]: r for r in (json.loads(l) for l in p.read_text().splitlines() if l)}


def auc_mw(y, s):
    y = np.asarray(y); s = np.asarray(s, float)
    if len(set(y.tolist())) < 2:
        return None, None
    a = float(roc_auc_score(y, s))
    p = float(mannwhitneyu(s[y == 1], s[y == 0], alternative="greater").pvalue)
    return a, p


def ties_info(y, s):
    y = np.asarray(y); s = np.asarray(s, float)
    def tied(v):
        u, c = np.unique(v, return_counts=True)
        return int(c[c > 1].sum()), int((c > 1).sum())
    pos, neg = s[y == 1], s[y == 0]
    tp_, gp = tied(pos); tn_, gn = tied(neg)
    cross = int(sum(np.sum(neg == v) for v in pos))
    return {"n_distinct_scores": int(len(np.unique(s))),
            "n_pos_in_tied_groups_within_pos": tp_, "n_tie_groups_within_pos": gp,
            "n_neg_in_tied_groups_within_neg": tn_, "n_tie_groups_within_neg": gn,
            "n_pos_neg_tied_pairs": cross,
            "n_pos_scores_shared_with_any_neg": int(sum(np.any(neg == v) for v in pos))}


def main():
    out = {"note": "aggregates only; generated by accord/prompt_sensitivity/audit_reversed.py"}
    g = pd.read_csv(GOLD)
    lab = dict(zip(g["pair_id"], g["label_clean"]))
    ids299 = g["pair_id"].tolist()
    ids253 = [i for i in ids299 if lab[i] != "ambiguous"]
    out["gold"] = {"n_299": len(ids299), "n_253": len(ids253),
                   "pos_299": int(sum(lab[i] == "contradiction" for i in ids299)),
                   "n_ambiguous": int(sum(lab[i] == "ambiguous" for i in ids299)),
                   "label_values": sorted(map(str, set(lab.values())))}
    ana = json.loads(ANALYSIS.read_text())

    cfg = PROMPTS["P_reversed"]
    out["vocab_P_reversed"] = {"pos_tokens_raw_yes": sorted(cfg["pos_tokens"]),
                               "neg_tokens_raw_no": sorted(cfg["neg_tokens"]),
                               "reversed_flag": cfg["reversed"],
                               "score_definition": "flag_logodds = -(logp(first top8 token in YES set) - logp(first top8 token in NO set)) = logp(No) - logp(Yes); floor -20 if absent"}

    # all nine cells: recompute
    nine = {}
    for m, tag in TAGS.items():
        for pr in ["P_asserting", "P_neutral", "P_reversed"]:
            r = load(tag, pr)
            ids = [i for i in ids253 if i in r and r[i]["flag_logodds"] is not None]
            y = [int(lab[i] == "contradiction") for i in ids]
            s = [r[i]["flag_logodds"] for i in ids]
            a, p = auc_mw(y, s)
            rep = ana["per_model_prompt"][m][pr]
            nine[f"{m}::{pr}"] = {"n": len(ids), "auroc_253": a, "mw_p_253": p,
                                 "reported_auroc": rep["auroc_253"], "reported_p": rep["mannwhitney_p_one_sided_253"],
                                 "auroc_match_4dp": round(a, 4) == round(rep["auroc_253"], 4),
                                 "p_match_4dp": round(p, 4) == round(rep["mannwhitney_p_one_sided_253"], 4),
                                 "auroc_ge_mde": a >= MDE}
    out["nine_cells"] = nine
    out["n_cells_auroc_ge_mde"] = int(sum(v["auroc_ge_mde"] for v in nine.values()))

    r = load(TAGS["llama3:8b"], "P_reversed")
    out["cache_llama_reversed"] = {"n_records": len(r), "all_299_present": all(i in r for i in ids299),
                                   "n_null_logodds": int(sum(r[i]["flag_logodds"] is None for i in r)),
                                   "n_null_label": int(sum(r[i]["flag_label"] is None for i in r))}
    res = {}
    for name, ids in [("G_253", ids253), ("G_299_ambiguous_as_negative", ids299)]:
        y = np.array([int(lab[i] == "contradiction") for i in ids])
        s = np.array([r[i]["flag_logodds"] for i in ids], float)
        h = np.array([r[i]["flag_label"] for i in ids], float)
        deg = np.array([bool(r[i]["degenerate"]) for i in ids])
        a, p = auc_mw(y, s)
        a_flip, p_flip = auc_mw(y, -s)
        d = {"n": int(len(ids)), "n_pos": int(y.sum()), "auroc": a, "mw_p_one_sided": p,
             "auroc_opposite_orientation": a_flip, "mw_p_opposite_orientation": p_flip}
        # hard label
        d["hard_label_auroc"] = float(roc_auc_score(y, h))
        d["hard_positive_rate"] = float(h.mean())
        d["hard_flag_rate_among_pos"] = float(h[y == 1].mean())
        d["hard_flag_rate_among_neg"] = float(h[y == 0].mean())
        d["mean_score_hard_flag1"] = float(s[h == 1].mean()) if (h == 1).any() else None
        d["mean_score_hard_flag0"] = float(s[h == 0].mean()) if (h == 0).any() else None
        d["median_score_hard_flag1"] = float(np.median(s[h == 1])) if (h == 1).any() else None
        d["median_score_hard_flag0"] = float(np.median(s[h == 0])) if (h == 0).any() else None
        d["n_hard1_score_le_0"] = int(((h == 1) & (s <= 0)).sum())
        d["n_hard0_score_ge_0"] = int(((h == 0) & (s >= 0)).sum())
        d["mean_score_pos"] = float(s[y == 1].mean()); d["mean_score_neg"] = float(s[y == 0].mean())
        d["median_score_pos"] = float(np.median(s[y == 1])); d["median_score_neg"] = float(np.median(s[y == 0]))
        # degeneracy
        d["n_degenerate"] = int(deg.sum())
        d["n_score_abs_ge_19"] = int((np.abs(s) >= 19).sum())
        keep = ~deg
        d["auroc_excl_degenerate"] = auc_mw(y[keep], s[keep])[0]
        d.update(ties_info(y, s))
        d["score_min"] = float(s.min()); d["score_max"] = float(s.max())
        # leverage
        k = int(np.ceil(0.10 * len(s)))
        order = np.argsort(-s, kind="mergesort")
        thresh = s[order[k - 1]]
        d["top10pct_k"] = k
        d["n_pos_in_top10pct_strict_topk_by_rank"] = int(y[order[:k]].sum())
        d["n_pos_score_ge_top10pct_threshold"] = int(((s >= thresh) & (y == 1)).sum())
        d["n_any_score_ge_top10pct_threshold"] = int((s >= thresh).sum())
        pos_idx = np.where(y == 1)[0]
        loo = []
        for j in pos_idx:
            m_ = np.ones(len(s), bool); m_[j] = False
            loo.append(auc_mw(y[m_], s[m_]))
        la = [x[0] for x in loo]; lp = [x[1] for x in loo]
        d["lopo_auroc_min"] = float(min(la)); d["lopo_auroc_max"] = float(max(la))
        d["lopo_p_at_min_auroc"] = float(lp[int(np.argmin(la))])
        d["lopo_p_max"] = float(max(lp))
        d["lopo_n_auroc_ge_mde"] = int(sum(x >= MDE for x in la))
        # positive ranks (normalized) sorted, no ids
        ranks = pd.Series(s).rank(ascending=False, method="average").to_numpy()
        d["pos_ranks_desc_sorted"] = sorted(float(x) for x in ranks[pos_idx])
        # bootstrap CI (stratified) and exact-ish permutation p
        rng = np.random.default_rng(42)
        neg_idx = np.where(y == 0)[0]
        bs = []
        for _ in range(5000):
            bi = np.concatenate([rng.choice(pos_idx, len(pos_idx)), rng.choice(neg_idx, len(neg_idx))])
            bs.append(roc_auc_score(y[bi], s[bi]))
        d["bootstrap95_auroc"] = [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
        d["bootstrap_frac_auroc_lt_mde"] = float(np.mean(np.array(bs) < MDE))
        perm = 0; B = 20000
        for _ in range(B):
            yp = rng.permutation(y)
            if roc_auc_score(yp, s) >= a - 1e-12:
                perm += 1
        d["permutation_p_one_sided"] = (perm + 1) / (B + 1)
        res[name] = d
    out["llama3_P_reversed"] = res

    # defect-free stratum (rules 3,4) via derived gold file
    df_out = {"source": str(DERIVED.relative_to(HOME)), "computable": False}
    try:
        dg = pd.read_csv(DERIVED)
        df_out["columns"] = list(dg.columns)
        rule_col = "rule" if "rule" in dg.columns else None
        if rule_col and "pair_id" in dg.columns:
            rule = dict(zip(dg["pair_id"], dg[rule_col]))
            df_ids = [i for i in ids299 if i in rule and rule[i] in (3, 4)]
            df_out["n_ids299_matched_in_derived"] = int(sum(i in rule for i in ids299))
            if "pharm_label" in dg.columns:
                pl = dict(zip(dg["pair_id"], dg["pharm_label"]))
                df_out["n_label_disagree_clean_vs_derived_pharm_label"] = int(
                    sum(str(pl[i]) != str(lab[i]) for i in ids299 if i in pl))
            for nm, ids in [("G_134_ambiguous_as_negative", df_ids),
                            ("rules34_ambiguous_dropped", [i for i in df_ids if lab[i] != "ambiguous"])]:
                y = np.array([int(lab[i] == "contradiction") for i in ids])
                s = np.array([r[i]["flag_logodds"] for i in ids], float)
                a, p = auc_mw(y, s)
                df_out[nm] = {"n": len(ids), "n_pos": int(y.sum()), "auroc": a, "mw_p_one_sided": p,
                              "mde_defect_free_registered": 0.8058}
            # complement stratum
            ids12 = [i for i in ids253 if i in rule and rule[i] in (1, 2)]
            y = np.array([int(lab[i] == "contradiction") for i in ids12])
            s = np.array([r[i]["flag_logodds"] for i in ids12], float)
            a, p = auc_mw(y, s)
            df_out["rules12_ambiguous_dropped"] = {"n": len(ids12), "n_pos": int(y.sum()), "auroc": a, "mw_p_one_sided": p}
            df_out["computable"] = True
    except Exception as exc:
        df_out["error_type"] = type(exc).__name__
    out["defect_free"] = df_out

    p253 = res["G_253"]["mw_p_one_sided"]
    out["multiplicity"] = {"bonferroni_threshold_9": 0.05 / 9, "p_253": p253,
                           "passes_bonferroni_9": p253 < 0.05 / 9,
                           "holm_sorted_p_9": sorted(v["mw_p_253"] for v in nine.values())}
    OUT.write_text(json.dumps(out, indent=2) + "\n")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        OUT.write_text(json.dumps({"failed": type(exc).__name__}) + "\n")
        raise SystemExit(1)
