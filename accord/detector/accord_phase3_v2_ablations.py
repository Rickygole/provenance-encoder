def evaluate_v2(model, loader, has_multitask=True):
    model.eval()
    all_preds, all_labels, all_r_preds, all_r_labels = [], [], [], []
    with torch.no_grad():
        for batch in loader:
            out = model(
                nursing_input_ids=batch['nursing_input_ids'].cuda(),
                nursing_attention_mask=batch['nursing_attention_mask'].cuda(),
                discharge_input_ids=batch['discharge_input_ids'].cuda(),
                discharge_attention_mask=batch['discharge_attention_mask'].cuda(),
                nursing_role_ids=batch['nursing_role_ids'].cuda(),
                nursing_intent_ids=batch['nursing_intent_ids'].cuda(),
                nursing_drug_class_ids=batch['nursing_drug_class_ids'].cuda(),
                nursing_temporal_pos=batch['nursing_temporal_pos'].cuda(),
                disease_ids=batch['disease_ids'].cuda(),
                discharge_role_ids=batch['discharge_role_ids'].cuda(),
                discharge_intent_ids=batch['discharge_intent_ids'].cuda(),
                discharge_drug_class_ids=batch['discharge_drug_class_ids'].cuda(),
                discharge_temporal_pos=batch['discharge_temporal_pos'].cuda(),
                drug_classes=batch['drug_classes'],
                rule_types=batch['rule_types']
            )
            all_preds.extend(torch.argmax(out['contradiction_logits'],-1).cpu().numpy())
            all_labels.extend(batch['labels'].numpy())
            if has_multitask and out['rule_logits'] is not None:
                all_r_preds.extend(torch.argmax(out['rule_logits'],-1).cpu().numpy())
                all_r_labels.extend(batch['rule_labels'].numpy())

    c_acc = accuracy_score(all_labels, all_preds)
    c_f1  = f1_score(all_labels, all_preds, average='macro', zero_division=0)
    r_f1  = f1_score(all_r_labels, all_r_preds, average='macro', zero_division=0) \
            if all_r_preds else 0.0
    return c_acc, c_f1, r_f1

def train_ablation(ModelClass, variant_name, has_multitask=True,
                   num_epochs=10, patience=3):
    torch.cuda.empty_cache()
    print(f'\n{"="*65}')
    print(f'Variant: {variant_name}')
    print(f'{"="*65}')

    model = ModelClass().cuda()

    # Load Stage 1 backbone weights
    stage1_state = torch.load(f'{OUT}/accord_stage1_best.pt', map_location='cpu')
    backbone_keys = {k.replace('backbone.',''):v
                     for k,v in stage1_state.items() if k.startswith('backbone.')}

    # Find backbone in model
    if hasattr(model, 'acne'):
        model.acne.backbone.load_state_dict(backbone_keys, strict=False)
    elif hasattr(model, 'backbone'):
        model.backbone.load_state_dict(backbone_keys, strict=False)

    # Apply LoRA
    lora_cfg = LoraConfig(r=16, lora_alpha=32, target_modules=['query','value'],
                          lora_dropout=0.1, bias='none')
    model = get_peft_model(model, lora_cfg)

    # Unfreeze novel components
    for name, param in model.named_parameters():
        if any(kw in name for kw in NOVEL_KEYWORDS):
            param.requires_grad = True

    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f'Trainable parameters: {trainable:,}')

    # Differential learning rates
    lora_params   = [p for n,p in model.named_parameters()
                     if p.requires_grad and not any(kw in n for kw in NOVEL_KEYWORDS)]
    novel_params  = [p for n,p in model.named_parameters()
                     if p.requires_grad and any(kw in n for kw in NOVEL_KEYWORDS)]
    optimizer = AdamW([
        {'params': lora_params,  'lr': 2e-5},
        {'params': novel_params, 'lr': 1e-4}
    ], weight_decay=0.01)

    total_steps = len(train_loader) * num_epochs
    scheduler = get_linear_schedule_with_warmup(
        optimizer, int(0.1*total_steps), total_steps)

    best_dev_f1, best_epoch, patience_counter = 0, 0, 0
    best_state = None

    print(f'{"Ep":<5}{"Loss":<10}{"C-F1":<10}{"R-F1":<10}{"Time":<8}')
    print('-' * 43)

    for epoch in range(num_epochs):
        model.train()
        total_loss = 0
        start = time.time()

        for batch in train_loader:
            optimizer.zero_grad()
            out = model(
                nursing_input_ids=batch['nursing_input_ids'].cuda(),
                nursing_attention_mask=batch['nursing_attention_mask'].cuda(),
                discharge_input_ids=batch['discharge_input_ids'].cuda(),
                discharge_attention_mask=batch['discharge_attention_mask'].cuda(),
                nursing_role_ids=batch['nursing_role_ids'].cuda(),
                nursing_intent_ids=batch['nursing_intent_ids'].cuda(),
                nursing_drug_class_ids=batch['nursing_drug_class_ids'].cuda(),
                nursing_temporal_pos=batch['nursing_temporal_pos'].cuda(),
                disease_ids=batch['disease_ids'].cuda(),
                discharge_role_ids=batch['discharge_role_ids'].cuda(),
                discharge_intent_ids=batch['discharge_intent_ids'].cuda(),
                discharge_drug_class_ids=batch['discharge_drug_class_ids'].cuda(),
                discharge_temporal_pos=batch['discharge_temporal_pos'].cuda(),
                drug_classes=batch['drug_classes'],
                rule_types=batch['rule_types']
            )
            labels_b = batch['labels'].cuda()
            confidences = batch['confidences'].cuda()
            c_loss = (contradiction_loss_fn(
                out['contradiction_logits'], labels_b) * confidences).mean()
            if has_multitask and out['rule_logits'] is not None:
                r_loss = rule_loss_fn(out['rule_logits'], batch['rule_labels'].cuda())
                loss = CONTRADICTION_WEIGHT * c_loss + RULE_TYPE_WEIGHT * r_loss
            else:
                loss = c_loss
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            scheduler.step()
            total_loss += loss.item()

        c_acc, c_f1, r_f1 = evaluate_v2(model, dev_loader, has_multitask)
        elapsed = time.time() - start
        print(f'{epoch+1:<5}{total_loss/len(train_loader):<10.4f}'
              f'{c_f1:<10.4f}{r_f1:<10.4f}{elapsed:.0f}s')

        if c_f1 > best_dev_f1:
            best_dev_f1 = c_f1
            best_epoch  = epoch + 1
            best_state  = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print(f'Early stopping at epoch {epoch+1}')
                break

    model.load_state_dict(best_state)
    test_c_acc, test_c_f1, test_r_f1 = evaluate_v2(model, test_loader, has_multitask)
    fname = variant_name.lower().replace(' ','_').replace('/','')
    torch.save(best_state, f'{OUT}/ablation_v2_{fname}.pt')

    print(f'\nBest dev F1: {best_dev_f1:.4f} at epoch {best_epoch}')
    print(f'Test contradiction F1: {test_c_f1:.4f} | Rule type F1: {test_r_f1:.4f}')

    return {
        'variant': variant_name,
        'best_dev_f1': float(best_dev_f1),
        'best_epoch': best_epoch,
        'test_accuracy': float(test_c_acc),
        'test_contradiction_f1': float(test_c_f1),
        'test_rule_f1': float(test_r_f1)
    }

