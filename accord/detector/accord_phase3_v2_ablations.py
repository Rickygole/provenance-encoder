class AsymmetricCrossNoteEncoder(nn.Module):
    def __init__(self, hidden_size=768, num_heads=8, dropout=0.1, authority_dampening=0.5):
        super().__init__()
        self.hidden_size = hidden_size
        self.backbone = AutoModel.from_pretrained(MODEL_NAME)
        self.nursing_to_discharge_attn = nn.MultiheadAttention(
            hidden_size, num_heads, dropout=dropout, batch_first=True)
        self.discharge_to_nursing_attn = nn.MultiheadAttention(
            hidden_size, num_heads, dropout=dropout, batch_first=True)
        self.authority_scale = nn.Parameter(torch.tensor([authority_dampening, 1.0]))
        self.norm_nursing = nn.LayerNorm(hidden_size)
        self.norm_discharge = nn.LayerNorm(hidden_size)
        self.dropout = nn.Dropout(dropout)
        self.nursing_proj = nn.Linear(hidden_size, hidden_size)
        self.discharge_proj = nn.Linear(hidden_size, hidden_size)

    def forward(self, nursing_input_ids, nursing_attention_mask,
                discharge_input_ids, discharge_attention_mask):
        nursing_out = self.backbone(nursing_input_ids, nursing_attention_mask)
        discharge_out = self.backbone(discharge_input_ids, discharge_attention_mask)
        nursing_seq = nursing_out.last_hidden_state
        discharge_seq = discharge_out.last_hidden_state
        nursing_key_mask = (nursing_attention_mask == 0)
        discharge_key_mask = (discharge_attention_mask == 0)
        nursing_cross, _ = self.nursing_to_discharge_attn(
            query=nursing_seq, key=discharge_seq, value=discharge_seq,
            key_padding_mask=discharge_key_mask)
        discharge_cross, _ = self.discharge_to_nursing_attn(
            query=discharge_seq, key=nursing_seq, value=nursing_seq,
            key_padding_mask=nursing_key_mask)
        nursing_cross = nursing_cross * self.authority_scale[0]
        discharge_cross = discharge_cross * self.authority_scale[1]
        nursing_fused = self.norm_nursing(nursing_seq + self.dropout(nursing_cross))
        discharge_fused = self.norm_discharge(discharge_seq + self.dropout(discharge_cross))
        return (self.nursing_proj(nursing_fused[:, 0, :]),
                self.discharge_proj(discharge_fused[:, 0, :]),
                self.authority_scale)

class ClinicalDecisionEncoder(nn.Module):
    def __init__(self, hidden_size=768, cde_dim=256):
        super().__init__()
        self.role_embedding = nn.Embedding(3, 64)
        self.intent_embedding = nn.Embedding(6, 64)
        self.drug_class_embedding = nn.Embedding(12, 64)
        self.temporal_projection = nn.Linear(1, 32)
        self.disease_embedding = nn.Embedding(4, 32)
        self.field_fusion = nn.Sequential(
            nn.Linear(256, cde_dim), nn.LayerNorm(cde_dim), nn.ReLU(), nn.Dropout(0.1))
        self.gate = nn.Sequential(nn.Linear(cde_dim+hidden_size, cde_dim), nn.Sigmoid())
        self.text_projection = nn.Linear(hidden_size, cde_dim)
    def forward(self, role_ids, intent_ids, drug_class_ids, temporal_position, disease_ids, text_repr):
        fields = torch.cat([
            self.role_embedding(role_ids), self.intent_embedding(intent_ids),
            self.drug_class_embedding(drug_class_ids),
            self.temporal_projection(temporal_position.float()),
            self.disease_embedding(disease_ids)], dim=-1)
        structured = self.field_fusion(fields)
        gate_values = self.gate(torch.cat([structured, text_repr], dim=-1))
        return gate_values * structured + (1-gate_values) * self.text_projection(text_repr), gate_values

class AuthorityTemporalConflictGraph(nn.Module):
    def __init__(self, node_dim=256, hidden_dim=256, num_heads=4):
        super().__init__()
        self.num_heads = num_heads
        self.head_dim = hidden_dim // num_heads
        self.authority_matrix = nn.Parameter(torch.tensor([[1.0,0.5],[1.5,1.0]]))
        self.query = nn.Linear(node_dim, hidden_dim)
        self.key = nn.Linear(node_dim, hidden_dim)
        self.value = nn.Linear(node_dim, hidden_dim)
        self.output_proj = nn.Linear(hidden_dim, node_dim)
        self.layer_norm = nn.LayerNorm(node_dim)
        self.dropout = nn.Dropout(0.1)
        self.conflict_scorer = nn.Sequential(
            nn.Linear(node_dim*2, node_dim), nn.ReLU(),
            nn.Dropout(0.1), nn.Linear(node_dim, 1), nn.Sigmoid())
    def forward(self, nursing_node, discharge_node):
        batch_size = nursing_node.shape[0]
        nodes = torch.stack([nursing_node, discharge_node], dim=1)
        auth_weight = self.authority_matrix[0, 1]
        Q = self.query(nodes).view(batch_size,2,self.num_heads,self.head_dim).transpose(1,2)
        K = self.key(nodes).view(batch_size,2,self.num_heads,self.head_dim).transpose(1,2)
        V = self.value(nodes).view(batch_size,2,self.num_heads,self.head_dim).transpose(1,2)
        scores = torch.matmul(Q,K.transpose(-2,-1))/(self.head_dim**0.5)*auth_weight
        attn = self.dropout(F.softmax(scores, dim=-1))
        attended = self.output_proj(
            torch.matmul(attn,V).transpose(1,2).contiguous().view(batch_size,2,-1))
        attended = self.layer_norm(nodes+attended)
        edge_repr = torch.cat([attended[:,0,:],attended[:,1,:]], dim=-1)
        return edge_repr, self.conflict_scorer(edge_repr), attn

class GuidelineGroundedHarmEstimator(nn.Module):
    def __init__(self, edge_dim=512, prior_dim=64, hidden_dim=256,
                 num_labels=3, num_rules=4, use_multitask=True):
        super().__init__()
        self.use_multitask = use_multitask
        self.guideline_bank = nn.Parameter(torch.randn(20, hidden_dim))
        self.cross_attention = nn.MultiheadAttention(
            hidden_dim, 4, dropout=0.1, batch_first=True)
        self.input_projection = nn.Sequential(
            nn.Linear(edge_dim+prior_dim, hidden_dim),
            nn.LayerNorm(hidden_dim), nn.ReLU(), nn.Dropout(0.1))
        self.contradiction_head = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim//2), nn.ReLU(),
            nn.Dropout(0.1), nn.Linear(hidden_dim//2, num_labels))
        self.harm_head = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim//2), nn.ReLU(),
            nn.Dropout(0.1), nn.Linear(hidden_dim//2, 1), nn.Sigmoid())
        self.explanation_head = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim), nn.ReLU(),
            nn.Dropout(0.1), nn.Linear(hidden_dim, hidden_dim))
        if use_multitask:
            self.rule_type_head = nn.Sequential(
                nn.Linear(hidden_dim, hidden_dim//2), nn.ReLU(),
                nn.Dropout(0.1), nn.Linear(hidden_dim//2, num_rules))
        self.layer_norm = nn.LayerNorm(hidden_dim)

    def forward(self, edge_repr, prior_vector):
        batch_size = edge_repr.shape[0]
        query = self.input_projection(
            torch.cat([edge_repr, prior_vector], dim=-1)).unsqueeze(1)
        keys = self.guideline_bank.unsqueeze(0).expand(batch_size,-1,-1)
        attended, attn = self.cross_attention(query=query, key=keys, value=keys)
        attended = self.layer_norm(attended.squeeze(1) + query.squeeze(1))
        rule_logits = self.rule_type_head(attended) if self.use_multitask else None
        return (self.contradiction_head(attended), rule_logits,
                self.harm_head(attended), self.explanation_head(attended), attn)

