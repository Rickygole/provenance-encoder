class ACCORDv2Full(nn.Module):
    def __init__(self, use_multitask=True):
        super().__init__()
        self.acne = AsymmetricCrossNoteEncoder()
        self.cde = ClinicalDecisionEncoder(768)
        self.atcg = AuthorityTemporalConflictGraph()
        self.gghe = GuidelineGroundedHarmEstimator(use_multitask=use_multitask)
        self.dropout = nn.Dropout(0.1)
        self.use_multitask = use_multitask

    def _prior(self, drug_classes, rule_types, device):
        pf = torch.zeros(len(drug_classes), 64, device=device)
        for i,(dc,rule) in enumerate(zip(drug_classes,rule_types)):
            pf[i,0]=DRUG_CLASS_DANGER.get(str(dc).lower().strip() if dc else 'unknown',1.0)
            pf[i,1]=rule/4.0
        return pf

    def forward(self, nursing_input_ids, nursing_attention_mask,
                discharge_input_ids, discharge_attention_mask,
                nursing_role_ids, nursing_intent_ids, nursing_drug_class_ids,
                nursing_temporal_pos, disease_ids,
                discharge_role_ids, discharge_intent_ids, discharge_drug_class_ids,
                discharge_temporal_pos, drug_classes, rule_types):
        device = nursing_input_ids.device
        n_text, d_text, auth = self.acne(
            nursing_input_ids, nursing_attention_mask,
            discharge_input_ids, discharge_attention_mask)
        n_node, _ = self.cde(nursing_role_ids, nursing_intent_ids, nursing_drug_class_ids,
            nursing_temporal_pos, disease_ids, self.dropout(n_text))
        d_node, _ = self.cde(discharge_role_ids, discharge_intent_ids, discharge_drug_class_ids,
            discharge_temporal_pos, disease_ids, self.dropout(d_text))
        prior = self._prior(drug_classes, rule_types, device)
        edge_repr, conflict_score, _ = self.atcg(n_node, d_node)
        c_logits, r_logits, harm, expl, _ = self.gghe(edge_repr, prior)
        return {'contradiction_logits': c_logits, 'rule_logits': r_logits,
                'harm_score': harm, 'conflict_score': conflict_score,
                'authority_scale': auth}

