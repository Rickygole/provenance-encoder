    'nursing_to_discharge_attn', 'discharge_to_nursing_attn',
    'norm_nursing', 'norm_discharge', 'nursing_proj', 'discharge_proj',
    'authority_scale', 'cde', 'atcg', 'gghe', 'text_proj'
